"""core/models/base.py: shared pieces for every model.

Navigation:
  UuidPk   `id` primary key generated by the database (gen_random_uuid(), PostgreSQL 13+)
"""
import uuid

from sqlalchemy import Uuid, text
from sqlalchemy.orm import Mapped, mapped_column


class UuidPk:
    """IDs are set by the database, never by application code (one source of truth)."""

    # Fetch database-set defaults (id, timestamps) in the INSERT's RETURNING, so a new object is
    # fully loaded and stays readable after the session closes (expire_on_commit=False).
    __mapper_args__ = {"eager_defaults": True}

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, server_default=text("gen_random_uuid()"))
